import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { test } from "node:test";
import ts from "typescript";

async function moduleFromTypescript(path) {
  const source = await readFile(new URL(path, import.meta.url), "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  });
  return import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
}
const { safeQrDataUri } = await moduleFromTypescript("../src/components/admin/qr.ts");
const { centavosToPesos } = await moduleFromTypescript("../src/components/admin/money.ts");

test("authenticator QR images accept self-contained SVG and raster data only", () => {
  const svg = '<svg xmlns="http://www.w3.org/2000/svg"><path d="M0 0h1v1"/></svg>';
  assert.equal(Boolean(safeQrDataUri(`data:image/svg+xml;utf8,${encodeURIComponent(svg)}`)), true);
  assert.equal(Boolean(safeQrDataUri(`data:image/svg+xml;utf-8,${svg}`)), true);
  assert.equal(
    Boolean(safeQrDataUri(`data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`)),
    true,
  );
  assert.equal(Boolean(safeQrDataUri("data:image/png;base64,aGVsbG8=")), true);
  for (const value of [
    "https://example.com/qr.png",
    "javascript:alert(1)",
    "data:image/svg+xml,%broken",
    "data:image/svg+xml,<svg><script>alert(1)</script></svg>",
    "data:image/svg+xml,<svg><path onclick='alert(1)'/></svg>",
    "data:image/svg+xml,<svg><image href='https://example.com'/></svg>",
    "data:image/svg+xml,<svg><path style='fill:url(https://example.com)'/></svg>",
  ])
    assert.equal(Boolean(safeQrDataUri(value)), false, value);
});

test("Supabase generator QR markup is normalized without accepting arbitrary XML or styles", () => {
  const cells = '<rect x="1" y="1" width="1" height="1" style="fill:black;stroke:none"/>'.repeat(
    1800,
  );
  const svg =
    '<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" style="fill:white;stroke:none"/>' +
    cells +
    "</svg>";
  const source = safeQrDataUri(`data:image/svg+xml;utf-8,${svg}`);
  assert.ok(source);
  const normalized = decodeURIComponent(source.split(",")[1]);
  assert.match(normalized, /^<svg/);
  assert.match(normalized, /fill="black" stroke="none"/);
  assert.doesNotMatch(normalized, /<\?|<!--|style=/);
  assert.ok(!source.includes("<") && !source.includes("#"));
  for (const unsafe of [
    svg.replace("fill:black;stroke:none", "fill:black;stroke:none;opacity:0"),
    svg.replace(
      '<?xml version="1.0"?>',
      '<!DOCTYPE svg [<!ENTITY x SYSTEM "https://example.com">]>',
    ),
    svg.replace("<!-- Generated by SVGo -->", "<!-- unexpected -->"),
    '<svg><rect style="fill:url(https://example.com);stroke:none"/></svg>',
  ]) {
    assert.equal(safeQrDataUri(`data:image/svg+xml;utf-8,${unsafe}`), undefined);
  }
  assert.equal(safeQrDataUri("x".repeat(512001)), undefined);
});

test("finance amounts render exact centavos including leading fractional zeroes", () => {
  assert.equal(centavosToPesos(0), "0.00");
  assert.equal(centavosToPesos(1), "0.01");
  assert.equal(centavosToPesos(10001), "100.01");
  assert.equal(centavosToPesos(9_000_000_000_000), "90000000000.00");
  for (const value of [-1, 1.5, NaN, Number.MAX_SAFE_INTEGER + 1])
    assert.throws(() => centavosToPesos(value));
});

const { moveSelectedImage } = await moduleFromTypescript("../src/components/admin/media-order.ts");
test("image order can move either way without losing selection or changing the original", () => {
  const selected = ["cover", "second", "third"];
  assert.deepEqual(moveSelectedImage(selected, 1, -1), ["second", "cover", "third"]);
  assert.deepEqual(moveSelectedImage(selected, 0, 1), ["second", "cover", "third"]);
  assert.deepEqual(selected, ["cover", "second", "third"]);
  for (const [index, direction] of [
    [0, -1],
    [2, 1],
    [-1, 1],
    [3, -1],
  ])
    assert.deepEqual(moveSelectedImage(selected, index, direction), selected);
  assert.deepEqual(moveSelectedImage([], 0, 1), []);
});
