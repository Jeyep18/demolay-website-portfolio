// Authenticator images must stay self-contained; never load an enrollment URL.
export function safeQrDataUri(value: string): string | undefined {
  if (value.length > 512000) return undefined;
  if (/^data:image\/(png|webp);base64,[a-zA-Z0-9+/=]+$/.test(value)) return value;
  const match = /^data:image\/svg\+xml(?:(;base64)|;(?:utf-?8|charset=utf-8))?,([\s\S]+)$/.exec(
    value,
  );
  if (!match) return undefined;
  try {
    const decoded = match[1] ? atob(match[2] || "") : decodeURIComponent(match[2] || "");
    // Supabase's QR generator emits this declaration/comment and two fixed cell styles.
    const svg = decoded
      .replace(/^\s*<\?xml version="1\.0"\?>\s*/, "")
      .replace(/^\s*<!-- Generated by SVGo -->\s*/, "")
      .replace(/\bstyle="fill:(black|white);stroke:none"/g, 'fill="$1" stroke="none"');
    const safe =
      /^\s*<svg\b/.test(svg) &&
      /<\/svg>\s*$/.test(svg) &&
      !/<\s*\/?\s*(?!svg\b|path\b|rect\b|g\b)[a-z!?:]/i.test(svg) &&
      !/\b(?:on[a-z]+|href|src|style)\s*=|url\s*\(|<!|<\?/i.test(svg);
    return safe ? `data:image/svg+xml,${encodeURIComponent(svg)}` : undefined;
  } catch {
    return undefined;
  }
}
